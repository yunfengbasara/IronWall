/**
 * 全局曲线和公式常量：等级、经验、波次成长、伤害、掉落。
 *
 * 单独一个文件，因为这里每一个数都不属于任何一个具体的角色、兵种或地图 —— 它们是这四张表
 * 之间的**换算关系**。调一个角色的攻击力只影响那个角色，调这里的 DEFENSE_SCALE 会同时改变
 * 场上每一次伤害结算。所以它们不该混在一起。
 */

import type { StatBonus, StatGrowth, UnitStats } from './types';

// ---------------------------------------------------------------- 等级与经验

/**
 * 等级上限。
 *
 * 三十级而不是无限：成长表是**绝对增量**的直线（见 StatGrowth），没有上限的直线迟早会让
 * 移动速度超过冲刺、攻击范围盖满半个屏幕。有上限，满级是多少一眼能算出来。
 */
export const MAX_LEVEL = 30;

/**
 * 曲线后段变陡的拐点。
 *
 * 平方那一项在前十级说了算，(level / EXP_STEEPEN) 那一项在后面接手：8 级上两项一样重，
 * 之后第二项越拉越开。改大这个数整条曲线变缓，改小变陡。
 */
export const EXP_STEEPEN = 8;

/**
 * 从第 level 级升到下一级需要多少经验。
 *
 * **前期快，中后期慢** —— 平方的底子上再乘一条自己也在长的系数，所以它比纯平方陡，
 * 又比指数可算（每一级要多少一眼能写出来）。
 *
 * 为什么不是纯平方：那一版离线量出来是**整条 30 级的梯子 4.4 局就爬完**（一局约
 * 196,000 点经验，而满级累计才 855,500）。注释里当年写的"一整局大约推到十级"从来没成立过 ——
 * 真实情况是一局直接冲到十九级。等级是这个游戏唯一的跨局长线，四局走完等于没有长线。
 *
 * 现在按一局 196,000 点算（演武荒原打满，按出兵表和经验表倒推）：
 *
 *   到 10 级   0.3 局   —— 第一局打到一半就到，开局那段"肉眼可见在变强"原样保留
 *   到 15 级   1.5 局
 *   到 20 级   5.7 局   —— 从这里开始才要"多打几局"
 *   到 25 级   16.6 局
 *   到 30 级   40 局    —— 满级是一个目标，不是一个下午
 */
export const expToNextLevel = (level: number): number => {
  if (level >= MAX_LEVEL) return Infinity;
  const steep = 1 + (level / EXP_STEEPEN) ** 2;
  return Math.round(100 * level * level * steep);
};

// ---------------------------------------------------------------- 伤害

/**
 * 防御的递减系数：防御 d 挡掉 d / (d + DEFENSE_SCALE) 的伤害。
 *
 * 用递减而不是"攻减防"：减法在两端都会出事 —— 防御高过攻击就完全免疫，防御低的时候一点
 * 防御又毫无感觉。递减公式里每一点防御都有用，而且永远挡不满。
 *
 * 100 这个量级是按玩家的攻击力定的（一级武将 120）：杂兵 4 点防御只挡掉 3.8%，一刀照样
 * 秒；持盾兵 16 点挡掉 13.8%，能看出"这个人硬"；末波的枪骑兵四十多点挡掉三成，得补第二刀。
 */
export const DEFENSE_SCALE = 100;

export const damageAfterDefense = (attack: number, defense: number): number =>
  attack * (1 - defense / (defense + DEFENSE_SCALE));

/**
 * 技能相对平砍的伤害倍率。
 *
 * skills.ts 的 power 字段本来只管"打中时溅多少碎片"（1 = 只飙血，2 = 血加甲片），那是画面
 * 上平砍和技能唯一的区别。现在它同时当伤害倍率用：power 每高一档，伤害乘一次这个数。两件
 * 事共用一个字段是有意的 —— 看着更狠的那一下本来就该更疼，分成两个字段迟早会调出"画面很
 * 炸但不疼"的招。
 */
export const SKILL_DAMAGE_PER_POWER = 2.2;

/** 暴击。技能更容易出，让大招偶尔炸出一个特别烫的数。 */
/**
 * 角色自带的那一招比别的招高多少伤害。
 *
 * 一局里自动攻击技是唯一不用抽、一直在挥的那一招，也是四个角色真正的分岔点（横扫、回旋、
 * 破空各是一种形状）。它要是到后期反而输给随便抽到的一张牌，这个角色就没有“自己的打法”了 ——
 * 最优解会变成“不管选谁，都靠主动技输出”。
 *
 * 加在伤害倍率上，所以碎片甩得多远、人掀得多远也跟着高一点（见 skillTier）—— 是故意的：
 * “最强的那一招”应该在每一个能看到的地方都稍微狠一点，而不是只在伤害数字上多一截。
 */
export const SIGNATURE_DAMAGE_BONUS = 0.1;

/**
 * 饮血：每造成一点伤害回多少血，按护身技的等级给。一级一份，满级五份。
 *
 * 0.007 看着极小，但它乘的是**整局的总输出**：一局打出几十万点伤害，一级就是几千点回血。
 * 而且它的回复量自动跟着人堆的密度走 —— 越危险的地方回得越快，而那正是它该有的形状。
 *
 * 上限卡在一局最大血上：回血不能超过上限（和丹同一条规矩）。
 *
 * 从 0.012 压到 0.007（满级从每点伤害回 6% 降到 3.5%）：人堆里一刀砍中几十个人，原来的
 * 满级饮血回得比末波整堆人打得还快 —— 于是走位、喝药、什么时候退出来全都不用想了，站在
 * 最密的地方按着平砍就是最优解。它该是"打得越狠越耐打"，不是"打得够狠就打不死"。
 */
export const LIFESTEAL_PER_LEVEL = 0.007;

/**
 * 回春：每一跳回血上限的几成（一秒一跳，见 REGEN_TICK）。再乘这一招的伤害倍率。
 *
 * 一级是 0.055 × 1.2 = 每秒 6.6%，十秒回六成六；满级 0.055 × 2.4 = 每秒一成三，
 * 十秒也就一成三的富余。它只是把你从'还能撑'拉回'还能打'。
 *
 * 从 0.1 压下来的理由：那一档的满级是每秒回四分之一上限，**四秒就从一丝血回满**，而这一招
 * 的冷却只有十四秒。于是它不再是"提前十秒按下去的保险"，是一个随叫随到的满血按钮 —— 挨打
 * 这件事不再有后果，而没有后果的挨打也就不值得躲。现在满级回满仍然要八秒，得在还撑得住的
 * 时候按，那才是这一招问的问题。
 */
export const MEND_HP_PER_TICK = 0.055;

/*
 * 狂暴的四个数。四件事一起发生，缺一件它就不成立。
 *
 * 输出那两项跟着等级长（乘伤害倍率），而掉血和降防不长 —— 升级该把这一招变得更值，
 * 而不是更危险。不然练满之后玩家反而不敢按。
 *
 * 整体的量级是**一起**往上抬的：以前是 +36% 攻击换每秒掉 4%，八秒一共掉三成二血 ——
 * 代价读得出来，收益读不出来，于是这张牌的正确打法是不按。现在两头都拉满：八秒里你
 * 是场上最疼的那个人，八秒完你剩一口气。那才是"狂暴"这两个字本来的意思。
 */
/** 狂暴期间攻击力多少。再乘这一招的伤害倍率：一级 +72%，满级 +144%。 */
export const BERSERK_ATTACK = 0.6;
/**
 * 出手频率多多少。同样乘伤害倍率：一级 +48%，满级 +96%。
 *
 * 和攻击力分开一项，因为这两件事在画面上是两回事：攻击力只改飘出来的数字，频率改的是
 * **人的动作**。狂暴期间玩家的角色挥得肉眼可见地快，不用看血条也知道自己现在在什么状态里 ——
 * 一个只加伤害的狂暴是一段除了掉血什么都看不出来的八秒。
 *
 * 这是全局唯一一处敢把攻击频率推到两倍的地方（技能升级那条明确避开了它，见 SKILL_LEVEL_RATE：
 * 长期两倍速会让人一直挥出一串看不清的残影）。它在这里成立，正因为它只有八秒，而且这八秒
 * 本来就该看起来不正常。
 */
export const BERSERK_ATTACK_SPEED = 0.4;
/** 防御掋多少。不跟等级走。 */
export const BERSERK_DEFENSE = -0.4;
/**
 * 每秒掉血上限的几成。一秒一跳，和回春、慢回的丹同一个节奏。
 *
 * 一成一跳，八秒掉掉八成上限 —— 满血按下去，结束时只剩两成。这个数是**故意疼的**：
 * 上面那两项把八秒变成了一局里输出最高的八秒，那这八秒就必须贵到需要先看一眼血条。
 * 代价小的时候这张牌只有一个正确答案（一直按或者一直不按），代价够大它才是个决定。
 *
 * **掉不死人，最低留一点。** 被自己的增益技耐死是一种很坏的死法 —— 玩家读不出那是一个
 * 决定的后果，只读得出“这个技能坑我”。卡在一点之后风险还在（一下就没），但死的那一下总是别人打的。
 */
export const BERSERK_HP_DRAIN = 0.1;

